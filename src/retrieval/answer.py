source_ids = []

# Validate IDs and build citations from retrieved documents

# For now, show metadata for all retrieved documents.
# The LLM is not selecting or inventing citation metadata.
citations = {}

for source_id, doc in enumerate(docs, start=1):
    citations[source_id] = {
        "book": doc.metadata.get("book"),
        "section": doc.metadata.get("section"),
        "page_start": doc.metadata.get("page_start"),
        "page_end": doc.metadata.get("page_end"),
    }

print("\nRetrieved citation metadata:")

for source_id, citation in citations.items():
    print(
        f"[Source {source_id} | "
        f"Book: {citation['book']} | "
        f"Section: {citation['section']} | "
        f"Pages: {citation['page_start']}-"
        f"{citation['page_end']}]"
    )

# Remove the Sources line from the answer text
answer_text = re.sub(
    r"\n?Sources:\s*\[[^\]]*\]",
    "",
    answer,
).strip()

# Remove inline citations generated by the LLM
answer_text = re.sub(
    r"\s*\[\d+\s*\|\s*Book:.*?\]",
    "",
    answer_text,
)

# Remove original text references such as [158] and [160]
answer_text = re.sub(
    r"\s*\[\d+\]",
    "",
    answer_text,
)

print("\nClean answer:")
print(answer_text)

print("\nQuestion:", question)
print("\nAnswer:\n", answer)
