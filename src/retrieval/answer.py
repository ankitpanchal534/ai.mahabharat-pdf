# v2
prompt = ChatPromptTemplate.from_template("""
Answer the question using ONLY the supplied context.

Question: {question}

Context:
{context}

Rules:
- Answer in 2-3 clear sentences.
- Paraphrase the source; do not copy incomplete sentences.
- Do not include quotations.
- Do not include citation labels or bracketed reference numbers.
- Do not add claims that the context does not support.
- If the context is insufficient, say so.

Return only the answer text.
""")

llm = OllamaLLM(model="gemma3:4b")

question = "What does Krishna teach Arjuna about work without attachment?"

# docs = vector_store.similarity_search(question, k=5)
docs = vector_store.max_marginal_relevance_search(
    question,
    k=5,
    fetch_k=20,
    lambda_mult=0.7,
)

for i, doc in enumerate(docs, start=1):
    print(
        i,
        doc.metadata.get("book"),
        doc.metadata.get("section"),
        doc.page_content[:120].replace("\n", " "),
    )

context = "\n\n".join(
    f"[Source {i} | Book: {doc.metadata.get('book')} | "
    f"Section: {doc.metadata.get('section')} | "
    f"Pages: {doc.metadata.get('page_start')}-"
    f"{doc.metadata.get('page_end')}]\n{doc.page_content}"
    for i, doc in enumerate(docs, start=1)
)

chain = prompt | llm
answer = chain.invoke({
    "context": context,
    "question": question,
})
# Extract the source IDs selected by the LLM
# match = re.search(r"Sources:\s*\[([^\]]*)\]", answer)

# if match:
